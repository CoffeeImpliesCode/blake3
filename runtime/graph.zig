//! Runtime route: one translated module, generated dispatch, and loader core.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time, and
//! linking the archive as well would make the linker demand them before `load`
//! ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in both configurations, because `LoadSource` and
//!             `LoadError` are this SDK's public types and must be the same
//!             types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding and the one load-time check.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             translated header itself as `c_native`.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=blake3_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "blake3_rt";

/// `extern` declarations that the C library provides and that must therefore
/// stay direct.
///
/// The translated header for this SDK is `blake3.h`, which includes only
/// `<stddef.h>` and `<stdint.h>` (`c/blake3.h:3-5`). On every C library except
/// MinGW's neither declares a function. MinGW's `<stdint.h>` includes
/// `<crtdefs.h>` (`any-windows-any/stdint.h:28`), which includes
/// `<corecrt.h>` (`any-windows-any/crtdefs.h:10`), which includes
/// `<_mingw.h>` (`any-windows-any/corecrt.h:10`); that header declares
/// `__mingw_get_crt_info` (`any-windows-any/_mingw.h:665`) and, on an
/// architecture for which the compiler has no `__prefetch` builtin,
/// `__prefetch` (`any-windows-any/_mingw.h:650`). Both are `SOURCE-CONFIRMED`
/// from the pinned Zig 0.16.0 headers and `OBSERVED` in the pinned translator's
/// own output for `x86_64-windows` and `thumb-windows` on 2026-10-04. Every
/// name in this list is a C library function, never one BLAKE3 exports, so it
/// cannot de-route a native symbol. The authoritative record of what *was*
/// routed is the `symbols` array in the generated dispatch.
const libc_noise =
    \\memcpy,memmove,memset,memcmp,memchr,strlen,strcmp,strncmp,strcpy,strncpy,
    \\strchr,strrchr,strstr,malloc,calloc,realloc,free,abort,exit,atexit,
    \\__mingw_get_crt_info,__prefetch
;

/// `extern` declarations the provider may legitimately not export.
///
/// This SDK declares none. The entry point upstream gates behind
/// `BLAKE3_USE_TBB` (`c/blake3.h:72-75`) is not declared at all, because neither
/// mode of this build defines that macro, so it is not in the translation and
/// not in the table. The list is spelled out so that adding a header with an
/// optional entry point is a build-file change with a name in it.
const provider_optional = "";

/// `extern` declarations this build does not require from a provider.
///
/// None. Every function `blake3.h` declares is expected from a provider, and a
/// provider that does not export one of them is refused rather than half used.
/// A name here would be routed into a nullable table field instead: its absence
/// would not fail the load, and its wrapper would stop the program by name.
/// Only `libc_noise` above keeps a declaration direct.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either
/// configuration. It costs a linked build two declarations and no code, since
/// nothing else in that module is referenced until a configuration actually
/// instantiates the loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports
/// the two types from it. Two instances would be two sets of types, and a
/// consumer would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}


const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};
fn createDispatchModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);
    // The translated header, under a name that says what it is. Every type and
    // constant in the dispatch is re-exported from here rather than restated, so
    // `c.blake3_hasher` in a facade and `c_native.blake3_hasher` in the dispatch
    // are one type.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// Nothing is cached across configurations: a different header configuration
/// produces a different translation step output, which produces a different
/// dispatch.
fn generateDispatch(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("blake3-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("blake3");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}